def ce(emoji: str) -> str:
    """Return <tg-emoji> HTML tag for a given emoji char (HTML parse mode only)."""
    eid = EMOJI_MAP.get(emoji)
    if eid:
        return f'<tg-emoji emoji-id="{eid}">{emoji}</tg-emoji>'
    return emoji


def apply_custom_emojis(text: str) -> str:
    """Replace all known unicode emojis in text with animated <tg-emoji> tags."""
    for emoji in _SORTED_EMOJIS:
        if emoji in text:
            eid = EMOJI_MAP[emoji]
            text = text.replace(emoji, f'<tg-emoji emoji-id="{eid}">{emoji}</tg-emoji>')
    return text


def md_to_html(text: str) -> str:
    """Convert basic Telegram Markdown to HTML.

    Handles: *bold*, `code`, [link](url), triple-backtick code blocks.
    Does NOT convert _italic_ to avoid breaking snake_case identifiers.
    """
    import re
    # Triple-backtick code blocks
    text = re.sub(r'```([^`]*?)```', r'<pre>\1</pre>', text, flags=re.DOTALL)
    # Inline code
    text = re.sub(r'`([^`\n]+?)`', r'<code>\1</code>', text)
    # Bold *text*
    text = re.sub(r'\*([^\*\n]+?)\*', r'<b>\1</b>', text)
    # Links [text](url)
    text = re.sub(r'\[([^\]]+?)\]\((https?://[^\)]+?)\)', r'<a href="\2">\1</a>', text)
    # Remove leftover backslash escapes from Markdown
    text = re.sub(r'\\([*_`\[\]()])', r'\1', text)
    return text
